-- CC-25: Bonus logistics tables (pickup_points, delivery_zones, time_slots) and 5-country seed data.

CREATE TABLE pickup_points (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id BIGINT       NOT NULL,
    name      VARCHAR(150) NOT NULL,
    address   VARCHAR(255) NOT NULL,
    CONSTRAINT fk_pickup_points_region FOREIGN KEY (region_id) REFERENCES regions (id)
);

CREATE INDEX idx_pickup_points_region_id ON pickup_points (region_id);

CREATE TABLE delivery_zones (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id    BIGINT         NOT NULL,
    name         VARCHAR(150)   NOT NULL,
    delivery_fee NUMERIC(14, 2) NOT NULL,
    CONSTRAINT fk_delivery_zones_region FOREIGN KEY (region_id) REFERENCES regions (id),
    CONSTRAINT ck_delivery_zones_fee CHECK (delivery_fee >= 0)
);

CREATE INDEX idx_delivery_zones_region_id ON delivery_zones (region_id);

CREATE TABLE time_slots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_date    DATE    NOT NULL,
    start_time   TIME    NOT NULL,
    capacity     INTEGER NOT NULL,
    booked_count INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_time_slots_date_time UNIQUE (slot_date, start_time),
    CONSTRAINT ck_time_slots_capacity CHECK (capacity >= 1),
    CONSTRAINT ck_time_slots_booked CHECK (booked_count >= 0 AND booked_count <= capacity)
);

CREATE INDEX idx_time_slots_date ON time_slots (slot_date);

