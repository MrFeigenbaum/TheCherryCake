-- CC-39: Bonus dining_tables and bookings schema with DB-level double-booking constraint.

CREATE TABLE dining_tables (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number VARCHAR(20) NOT NULL,
    seats        INTEGER     NOT NULL,
    CONSTRAINT uq_dining_tables_number UNIQUE (table_number),
    CONSTRAINT ck_dining_tables_seats CHECK (seats >= 1 AND seats <= 12)
);

CREATE TABLE bookings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_number VARCHAR(50)  NOT NULL,
    table_id       BIGINT       NOT NULL,
    booking_date   DATE         NOT NULL,
    booking_time   TIME         NOT NULL,
    guests         INTEGER      NOT NULL,
    name           VARCHAR(150) NOT NULL,
    phone          VARCHAR(50)  NOT NULL,
    email          VARCHAR(150) NOT NULL,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_bookings_number UNIQUE (booking_number),
    CONSTRAINT uq_bookings_table_slot UNIQUE (table_id, booking_date, booking_time),
    CONSTRAINT fk_bookings_table FOREIGN KEY (table_id) REFERENCES dining_tables (id),
    CONSTRAINT ck_bookings_guests CHECK (guests >= 1 AND guests <= 12)
);

CREATE INDEX idx_bookings_date_time ON bookings (booking_date, booking_time);

