-- CC-6: orders and order_items tables.
-- Money amounts use NUMERIC(14, 2) to safely hold UZS values; rates use NUMERIC(5, 4).

CREATE TABLE orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number    VARCHAR(50)    NOT NULL,
    order_date      DATE           NOT NULL,
    region_id       BIGINT         NOT NULL,
    customer_name   VARCHAR(150)   NOT NULL,
    phone           VARCHAR(50)    NOT NULL,
    email           VARCHAR(150)   NOT NULL,
    subtotal        NUMERIC(14, 2) NOT NULL,
    vat_rate        NUMERIC(5, 4)  NOT NULL DEFAULT 0.0000,
    vat_amount      NUMERIC(14, 2) NOT NULL,
    amount_incl_vat NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    discount_rate   NUMERIC(5, 4)  NOT NULL DEFAULT 0.0000,
    discount_amount NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    delivery_fee    NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    total           NUMERIC(14, 2) NOT NULL,
    currency_code   VARCHAR(3)     NOT NULL DEFAULT 'UZS',
    created_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_orders_order_number UNIQUE (order_number),
    CONSTRAINT fk_orders_region FOREIGN KEY (region_id) REFERENCES regions (id),
    CONSTRAINT ck_orders_subtotal CHECK (subtotal >= 0),
    CONSTRAINT ck_orders_vat_amount CHECK (vat_amount >= 0),
    CONSTRAINT ck_orders_discount_amount CHECK (discount_amount >= 0),
    CONSTRAINT ck_orders_delivery_fee CHECK (delivery_fee >= 0),
    CONSTRAINT ck_orders_total CHECK (total >= 0)
);

CREATE INDEX idx_orders_order_date ON orders (order_date);
CREATE INDEX idx_orders_region_id ON orders (region_id);

CREATE TABLE order_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT         NOT NULL,
    product_id      BIGINT         NOT NULL,
    product_name    VARCHAR(150)   NOT NULL,
    quantity        INTEGER        NOT NULL,
    unit_price      NUMERIC(14, 2) NOT NULL,
    modifiers_price NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    modifiers_json  TEXT,
    line_total      NUMERIC(14, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_order_items_quantity CHECK (quantity >= 1),
    CONSTRAINT ck_order_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_items_line_total CHECK (line_total >= 0)
);

CREATE INDEX idx_order_items_order_id ON order_items (order_id);

